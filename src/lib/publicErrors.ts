export function publicHttpErrorMessage(code: string, status: number): string {
  if (Object.prototype.hasOwnProperty.call(messages, code)) return messages[code];
  if (status === 401) return '请重新登录后继续。';
  if (status === 429) return '请求较多，请稍后重试。';
  return FALLBACK_MESSAGE;
}

export function describePublicError(error: unknown, fallback = FALLBACK_MESSAGE): string {
  return error instanceof PublicUiError ? error.message : fallback;
}
